import DialysisSession from '../models/DialysisSession.js';
import BillingClaim from '../models/BillingClaim.js';
import MedicationAdministration from '../models/MedicationAdministration.js';
import Order from '../models/Order.js';
import { DIALYSIS_PROCEDURE, drugCodeFor, RADIOLOGY_LINE } from '../utils/billingCodes.js';

const monthStr = (d) => {
  const x = new Date(d);
  return `${x.getFullYear()}-${String(x.getMonth() + 1).padStart(2, '0')}`;
};

/**
 * Build the itemised service lines for one completed session: the dialysis
 * procedure, every medication given during it (drugs + IVs), and any radiology
 * ordered for that patient the same day.
 */
async function buildLineItems(session) {
  const lineItems = [];

  // 1) Dialysis procedure — one per session.
  lineItems.push({
    code: DIALYSIS_PROCEDURE.code,
    description: DIALYSIS_PROCEDURE.description,
    category: 'dialysis',
    quantity: 1,
    unitAmount: DIALYSIS_PROCEDURE.fee,
    amount: DIALYSIS_PROCEDURE.fee,
  });

  // 2) Medications administered during the session (drugs + IVs).
  const meds = await MedicationAdministration.find({ session: session._id, status: 'active' }).lean();
  meds.forEach((m) => {
    const dc = drugCodeFor(m.name);
    const qty = Number(m.quantity) || 1;
    const isIV = String(m.route || '').toUpperCase() === 'IV';
    lineItems.push({
      code: dc.code,
      description: `${m.name}${m.dose ? ` ${m.dose}${m.unit || ''}` : ''}${isIV ? ' (IV)' : ''}`,
      category: isIV ? 'iv' : 'drug',
      quantity: qty,
      unitAmount: dc.fee,
      amount: dc.fee * qty,
    });
  });

  // 3) Radiology ordered for this patient on the session day.
  const base = session.sentToBillerAt || session.completedAt || session.updatedAt || new Date();
  const dayStart = new Date(base); dayStart.setHours(0, 0, 0, 0);
  const dayEnd = new Date(dayStart); dayEnd.setDate(dayStart.getDate() + 1);
  const pid = session.patient?._id || session.patient;
  if (pid) {
    const rad = await Order.find({ patient: pid, orderType: 'radiology', orderDate: { $gte: dayStart, $lt: dayEnd } }).lean();
    rad.forEach((o) => lineItems.push({
      code: RADIOLOGY_LINE.code,
      description: o.name || 'Radiology',
      category: 'radiology',
      quantity: Number(o.quantity) || 1,
      unitAmount: RADIOLOGY_LINE.fee,
      amount: RADIOLOGY_LINE.fee,
    }));
  }

  return lineItems;
}

/** Create the claim for one completed session (if it doesn't already have one). */
export async function createClaimForSession(sessionOrId) {
  const s = sessionOrId?._id
    ? sessionOrId
    : await DialysisSession.findById(sessionOrId).populate('patient', 'firstName lastName mrn insurance').lean();
  if (!s || s.status !== 'completed') return false;

  const exists = await BillingClaim.findOne({ session: s._id }).lean();
  if (exists) return false;

  const lineItems = await buildLineItems(s);
  const amount = lineItems.reduce((sum, l) => sum + (Number(l.amount) || 0), 0);

  try {
    await BillingClaim.create({
      patient: s.patient?._id || s.patient,
      session: s._id,
      month: monthStr(s.sentToBillerAt || s.completedAt || new Date()),
      amount,
      status: 'pending',
      insuranceProvider: s.patient?.insurance?.providerName || s.patient?.insurance?.payerName || undefined,
      lineItems,
      autoGenerated: true,
      notes: 'Auto-generated on dialysis completion.',
    });
    await MedicationAdministration.updateMany({ session: s._id }, { $set: { billingStatus: 'billed' } });
    return true;
  } catch (e) {
    return false; // unique-session race / validation — skip
  }
}

/**
 * Generate billing claims for every completed session that doesn't yet have a
 * claim — immediately (no delay). Returns the count created.
 */
export async function generateDueClaims() {
  const sessions = await DialysisSession.find({ status: 'completed' })
    .populate('patient', 'firstName lastName mrn insurance')
    .lean();

  let created = 0;
  for (const s of sessions) {
    if (await createClaimForSession(s)) created += 1;
  }
  return created;
}
